for (const id of [...folderIconIds]) {
  if (!id.endsWith('-open') && id !== 'folder') folderIconIds.push(`${id}-open`);
}

const iconIds = [...new Set([...fileIconIds, ...folderIconIds])].sort();
const allowedIconIds = new Set(iconIds);
const manifest = generateManifest({
  activeIconPack: 'react',
  folders: { theme: 'specific', associations: {} },
  files: { associations: {} },
  languages: { associations: {} },
});

function iconSvg(id) {
  const definition = manifest.iconDefinitions[id];
  if (!definition?.iconPath) throw new Error(`Material icon definition is missing: ${id}`);
  const fileName = definition.iconPath.split('/').at(-1);
  return readFileSync(join(upstreamRoot, 'icons', fileName), 'utf8').trim();
}

function filteredAssociations(source) {
  return Object.fromEntries(
    Object.entries(source ?? {})
      .filter(([, iconId]) => allowedIconIds.has(iconId))
      .map(([key, iconId]) => [key.toLowerCase(), iconId])
      .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0)),
  );
}

const output = `// Generated by scripts/generate-material-icons.mjs from material-icon-theme ${upstreamVersion}.
// Do not edit this file by hand.

export const MATERIAL_ICON_SVGS = ${JSON.stringify(
  Object.fromEntries(iconIds.map((id) => [id, iconSvg(id)])),
  null,
  2,
)} as const;

export const MATERIAL_FILE_NAME_ICONS = ${JSON.stringify(filteredAssociations(manifest.fileNames), null, 2)} as const;

export const MATERIAL_FILE_EXTENSION_ICONS = ${JSON.stringify(filteredAssociations(manifest.fileExtensions), null, 2)} as const;

export const MATERIAL_FOLDER_NAME_ICONS = ${JSON.stringify(filteredAssociations(manifest.folderNames), null, 2)} as const;

export const MATERIAL_OPEN_FOLDER_NAME_ICONS = ${JSON.stringify(filteredAssociations(manifest.folderNamesExpanded), null, 2)} as const;
`;

writeFileSync(join(packageRoot, 'src', 'material-icons.generated.ts'), output);
